import Foundation
func check(_ condition: Bool,_ message: String) { if !condition { fatalError(message) } }
let start=Date(timeIntervalSince1970:1000)
let verified=UUID(),other=UUID()
func ad(_ id:UUID,_ name:String?=nil,_ peripheralName:String?=nil,_ bytes:Data?=nil)->DiscoveryAdvertisement {
 DiscoveryAdvertisement(identifier:id,localName:name,peripheralName:peripheralName,services:["180F"],manufacturer:bytes,connectable:nil,rssi:-63)
}
var model=DiscoveryObservationModel(verifiedIdentifier:verified,startedAt:start)
model.observe(ad(other,"Private headphones"),at:start)
check(model.otherAdvertisementCount==1 && model.rows.isEmpty,"non-target identities excluded")
model.observe(ad(verified),at:start)
model.observe(ad(other,"Insta360 Mic Pro TX TEST01",nil,Data([0x00,0xff])),at:start.addingTimeInterval(59.9))
model.observe(ad(other,nil,"TEST01"),at:start)
check(model.targetAdvertisementCount==3,"verified UUID, local advertisement and cached target name match")
model.observe(ad(verified),at:start.addingTimeInterval(60))
model.observe(ad(verified),at:start.addingTimeInterval(-1))
check(model.targetAdvertisementCount==3,"outside bounded time window ignored")
check(model.rows[1]["manufacturer_hex"] as? String == "00ff","manufacturer hex preserves bytes")
let report=model.report(endedAt:start.addingTimeInterval(60),reason:"deadline")
let json=try! JSONSerialization.data(withJSONObject:report)
let text=String(decoding:json,as:UTF8.self)
check(!text.contains("Private headphones") && !text.contains(other.uuidString),"private non-target names/UUIDs not serialized")
check(report["connections_initiated"] as? Bool==false,"observation cannot claim connection")
for _ in 0..<600 { model.observe(ad(verified,"TEST01",nil,Data(repeating:0xab,count:600)),at:start) }
check(model.rows.count==512 && model.targetAdvertisementCount==603,"storage bounded, callbacks counted")
check((model.rows.last?["manufacturer_hex"] as? String)?.count==1024,"manufacturer payload bounded")
check(model.report(endedAt:start.addingTimeInterval(60),reason:"deadline")["target_rows_truncated"] as? Bool==true,"truncation explicit")
var noVerified=DiscoveryObservationModel(verifiedIdentifier:nil,startedAt:start)
noVerified.observe(ad(other),at:start)
check(noVerified.rows.isEmpty,"nil verified identifier does not match anonymous devices")
let serviceCandidate=DiscoveryAdvertisement(identifier:other,localName:"Unknown device",peripheralName:nil,services:[DiscoveryObservationModel.verifiedServiceUUID.uppercased()],manufacturer:Data([1,2,3]),connectable:true,rssi:-50)
noVerified.observe(serviceCandidate,at:start)
check(noVerified.unverifiedServiceCandidateCount==1 && noVerified.targetAdvertisementCount==0 && noVerified.rows.isEmpty,"service-only identity is an unverified count, never a target row")
noVerified.observeSystemConnected([(verified,"TEST01","connected"),(other,"Private headphones","connected"),(verified,"TEST01","connected")],at:start)
check(noVerified.systemConnectedTargetCount==1 && noVerified.systemConnectedTargetStates==["connected"],"system snapshot filters identity and deduplicates")
noVerified.observeSystemConnected([],at:start.addingTimeInterval(1))
check(noVerified.systemConnectedTargetCount==1,"system enumeration recorded once, no loops")
let systemJSON=String(decoding:try! JSONSerialization.data(withJSONObject:noVerified.report(endedAt:start.addingTimeInterval(60),reason:"deadline")),as:UTF8.self)
check(!systemJSON.contains("Private headphones") && !systemJSON.contains("Unknown device") && !systemJSON.contains(other.uuidString) && !systemJSON.contains(verified.uuidString),"candidate and system identities not serialized")
var late=DiscoveryObservationModel(verifiedIdentifier:verified,startedAt:start)
late.observeSystemConnected([(verified,nil,"connected")],at:start.addingTimeInterval(60))
check(late.systemEnumerationAt==nil,"late system snapshot excluded by same deadline")
check(late.report(endedAt:start.addingTimeInterval(60),reason:"deadline")["system_connected_target_count"] is NSNull,"not enumerated remains unknown rather than zero")
print("PASS: target filters, non-target privacy, 60-second boundary, bounded records/payload and JSON serialization")
