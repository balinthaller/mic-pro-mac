import Foundation
var stream = SerialPacketStream()
let noise = Data([0xFC,0xEF,0xFD,0xF3,0xFF,0,6,0,5,4,2,0,0,0])
assert(stream.append(noise.prefix(5)).isEmpty)
let first = stream.append(noise.dropFirst(5))
assert(first.count == 1 && serialNoiseValue(first[0]) == 2)
let audio = Data([0xFC,0xEF,0xFD,0xF1,0xFF,0xFF,3,0,9,8,7])
let subsequent = stream.append(audio + noise + noise)
assert(subsequent.count == 2 && subsequent.allSatisfy { serialNoiseValue($0) == 2 })
assert(stream.append(Data([0,8,0xFC,0xEF,0xFD,0xF3,0,0,0xFF,0xFF]) + noise).count == 1)
assert(serialNoiseValue(SerialPacket(command: 0xF3, payload: Data([5,4,3,0,0,0]))) == nil)
assert(serialNoiseRequest() == Data([0xFE,0xEF,0xFD,0xF3,0xFF,0,6,0,5,4,0,0,0,0]))
assert(serialNoiseRequest(1)[8] == 0x82 && serialNoiseRequest(1)[10] == 1)
