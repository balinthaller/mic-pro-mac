import Foundation
func expect(_ value: Bool,_ message: String) { if !value { fatalError(message) } }
var state = DeviceHandoffState()
expect(!state.beginRelease(busy:true),"busy transfer must reject without changing intent")
expect(!state.suppressAppConnections,"busy rejection must retain Mac intent")
expect(state.beginRelease(busy:false),"release starts")
expect(state.suppressAppConnections,"intent suppresses reconnect before cancellation")
expect(!state.observeRelease(classicConnected:true,controlConnected:false,timedOut:false),"audio disconnect request is not completion")
expect(!state.observeRelease(classicConnected:false,controlConnected:true,timedOut:false),"BLE release must be observed too")
expect(state.observeRelease(classicConnected:false,controlConnected:false,timedOut:false),"all channels released")
expect(state.phase == .released,"released state")
expect(!state.returnToMac(busy:true) && state.suppressAppConnections,"busy return does not permit background reconnect")
expect(!state.observeRelease(classicConnected:true,controlConnected:false,timedOut:false) && state.suppressAppConnections,"external reconnection must not clear user intent")
var restarted = DeviceHandoffState(suppressed:state.suppressAppConnections)
expect(restarted.phase == .unconfirmed && restarted.suppressAppConnections,"restart preserves intent but does not claim release was observed")
expect(restarted.beginRelease(busy:false),"retry release")
expect(restarted.observeRelease(classicConnected:true,controlConnected:false,timedOut:true),"timeout ends pending operation")
expect(restarted.phase == .unconfirmed && restarted.suppressAppConnections,"timeout is explicit unknown and does not permit reconnection")
expect(restarted.returnToMac(busy:false) && !restarted.suppressAppConnections,"explicit return permits connection")
print("PASS: transfer exclusivity, observed release, timeout, external connection, restart and explicit return")
